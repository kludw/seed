//go:build ignore

// Generates lib/regex/regex_tables.c, the Unicode tables of package regex,
// from Go's unicode package, so that \p{...} classes and (?i) case folding
// agree with Go's regexp:
//
//	go run lib/regex/gen/tables.go > lib/regex/regex_tables.c
package main

import (
	"fmt"
	"os"
	"sort"
	"strings"
	"unicode"
)

// The scripts that \p{Name} knows besides the general categories.
var scripts = []string{
	"Arabic", "Armenian", "Bengali", "Common", "Cyrillic", "Devanagari", "Georgian", "Greek",
	"Gujarati", "Gurmukhi", "Han", "Hangul", "Hebrew", "Hiragana", "Inherited", "Kannada",
	"Katakana", "Khmer", "Lao", "Latin", "Malayalam", "Myanmar", "Sinhala", "Tamil", "Telugu",
	"Thai", "Tibetan",
}

func ranges(t *unicode.RangeTable) [][2]rune {
	var out [][2]rune
	add := func(lo, hi rune) {
		if n := len(out); n > 0 && out[n-1][1]+1 == lo {
			out[n-1][1] = hi
			return
		}
		out = append(out, [2]rune{lo, hi})
	}
	for _, r := range t.R16 {
		for c := rune(r.Lo); c <= rune(r.Hi); c += rune(r.Stride) {
			if r.Stride == 1 {
				add(c, rune(r.Hi))
				break
			}
			add(c, c)
		}
	}
	for _, r := range t.R32 {
		for c := rune(r.Lo); c <= rune(r.Hi); c += rune(r.Stride) {
			if r.Stride == 1 {
				add(c, rune(r.Hi))
				break
			}
			add(c, c)
		}
	}
	return out
}

func main() {
	w := os.Stdout
	fmt.Fprintf(w, "/* Unicode tables of package regex (Unicode %s): the general categories\n", unicode.Version)
	fmt.Fprintf(w, " * and some scripts for \\p{...}, and simple case folding for (?i).\n")
	fmt.Fprintf(w, " * Generated by lib/regex/gen/tables.go from Go's unicode package, so that\n")
	fmt.Fprintf(w, " * they agree with Go's regexp. Do not edit. */\n")
	fmt.Fprintf(w, "#include \"seed.h\"\n\n#include <stdint.h>\n#include <string.h>\n\n")

	type table struct {
		name string
		rs   [][2]rune
	}
	var tabs []table
	var cats []string
	for name := range unicode.Categories {
		cats = append(cats, name)
	}
	sort.Strings(cats)
	for _, name := range cats {
		if len(name) == 1 {
			continue // the union of its two-letter categories, checked below
		}
		tabs = append(tabs, table{name, ranges(unicode.Categories[name])})
	}
	// One-letter categories are unions of the two-letter ones: check it.
	for _, name := range cats {
		if len(name) != 1 {
			continue
		}
		want := unicode.Categories[name]
		for c := rune(0); c <= unicode.MaxRune; c++ {
			in := false
			for _, t := range tabs {
				if strings.HasPrefix(t.name, name) && unicode.Is(unicode.Categories[t.name], c) {
					in = true
					break
				}
			}
			if in != unicode.Is(want, c) {
				fmt.Fprintf(os.Stderr, "category %s is not the union of its subcategories at %U\n", name, c)
				os.Exit(1)
			}
		}
	}
	for _, name := range scripts {
		t, ok := unicode.Scripts[name]
		if !ok {
			fmt.Fprintf(os.Stderr, "no script %s\n", name)
			os.Exit(1)
		}
		tabs = append(tabs, table{name, ranges(t)})
	}
	for _, t := range tabs {
		fmt.Fprintf(w, "static const int32_t rx_tab_%s[] = {", t.name)
		for i, r := range t.rs {
			if i%6 == 0 {
				fmt.Fprintf(w, "\n ")
			}
			fmt.Fprintf(w, " 0x%x, 0x%x,", r[0], r[1])
		}
		fmt.Fprintf(w, "\n};\n")
	}
	fmt.Fprintf(w, "\nstatic const struct {\n  const char *name;\n  const int32_t *pairs;\n  int n;\n} rx_tabs[] = {\n")
	for _, t := range tabs {
		fmt.Fprintf(w, "  {\"%s\", rx_tab_%s, %d},\n", t.name, t.name, len(t.rs))
	}
	fmt.Fprintf(w, "};\n\n")

	// Simple case folding: entries {lo, hi, kind, delta}, sorted and
	// disjoint. kind 0: unicode.SimpleFold(c) == c + delta for every c from
	// lo to hi; kind 1: upper and lower case alternate from lo, so c folds
	// to c + 1 when c - lo is even and to c - 1 when it is odd.
	type fold struct{ lo, hi, kind, delta rune }
	var folds []fold
	for c := rune(0); c <= unicode.MaxRune; c++ {
		f := unicode.SimpleFold(c)
		if f == c {
			continue
		}
		d := f - c
		if n := len(folds); n > 0 && c == folds[n-1].hi+1 {
			last := &folds[n-1]
			if last.kind == 0 && last.delta == d {
				last.hi = c
				continue
			}
			if last.kind == 0 && last.lo == last.hi && last.delta == 1 && d == -1 {
				last.hi = c
				last.kind = 1
				last.delta = 0
				continue
			}
			if last.kind == 1 && ((c-last.lo)%2 == 0 && d == 1 || (c-last.lo)%2 == 1 && d == -1) {
				last.hi = c
				continue
			}
		}
		folds = append(folds, fold{c, c, 0, d})
	}
	fmt.Fprintf(w, "static const int32_t rx_folds[][4] = {")
	for i, f := range folds {
		if i%3 == 0 {
			fmt.Fprintf(w, "\n ")
		}
		fmt.Fprintf(w, " {0x%x, 0x%x, %d, %d},", f.lo, f.hi, f.kind, f.delta)
	}
	fmt.Fprintf(w, "\n};\n\n")
	fmt.Fprintf(w, `/* unicode.SimpleFold: the next rune of c's case-folding orbit, or c. */
static int32_t rx_simple_fold(int32_t c) {
  int lo = 0, hi = (int)(sizeof rx_folds / sizeof rx_folds[0]);
  while (lo < hi) {
    int m = (lo + hi) / 2;
    if (rx_folds[m][1] < c) lo = m + 1;
    else hi = m;
  }
  if (lo == (int)(sizeof rx_folds / sizeof rx_folds[0]) || rx_folds[lo][0] > c) return c;
  if (rx_folds[lo][2] == 0) return c + rx_folds[lo][3];
  return (c - rx_folds[lo][0]) %% 2 == 0 ? c + 1 : c - 1;
}

/* The ranges (pairs lo, hi) of the category or script called name[0..len),
 * or NULL. */
static const int32_t *rx_unicode_table(const char *name, size_t len, int *n) {
  for (size_t i = 0; i < sizeof rx_tabs / sizeof rx_tabs[0]; i++) {
    if (strlen(rx_tabs[i].name) == len && memcmp(rx_tabs[i].name, name, len) == 0) {
      *n = rx_tabs[i].n;
      return rx_tabs[i].pairs;
    }
  }
  return NULL;
}

/* The two-letter categories, for the one-letter ones (\pL is Ll, Lm, Lo,
 * Lt and Lu together). */
static int rx_unicode_category_count(void) { return %d; }
static const char *rx_unicode_category_name(int i) { return rx_tabs[i].name; }
`, countCats(tabs))
	_ = strings.ToLower
}

func countCats(tabs interface{}) int {
	n := 0
	for name := range unicode.Categories {
		if len(name) == 2 {
			n++
		}
	}
	return n
}
